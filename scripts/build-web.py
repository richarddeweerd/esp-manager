#!/usr/bin/env python3
"""Build the web pages into C++ headers that compile them into the firmware.

Usage:
    scripts/build-web.py           # rewrite src/web/generated/*.h
    scripts/build-web.py --check   # fail if a header doesn't match its sources (what CI runs)

Each page in src/web/<page>/ becomes one HTML file: style.css and app.js are inlined, and the
text from src/web/strings.en.json replaces the /*STRINGS*/ marker in app.js. The result is
gzipped and written as a byte array to src/web/generated/<Name>Page.h, which is committed, so
building the library never needs Python.

--check compares the page inside each header with a fresh build, not the gzip bytes, so a
different zlib version doesn't make it fail. Standard library only.
"""

import argparse
import gzip
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "src" / "web"
GENERATED = WEB / "generated"
STRINGS = WEB / "strings.en.json"

# (source folder, header name, C++ name)
PAGES = [
    ("portal", "PortalPage.h", "kPortalPage"),
]

BYTE = re.compile(r"0x([0-9a-f]{2})")


def build_page(folder):
    """Returns the page in src/web/<folder>/ as one HTML document."""
    source = WEB / folder
    html = (source / "index.html").read_text(encoding="utf-8")
    css = (source / "style.css").read_text(encoding="utf-8")
    js = (source / "app.js").read_text(encoding="utf-8")
    strings = json.loads(STRINGS.read_text(encoding="utf-8"))

    if "/*STRINGS*/ {}" not in js:
        sys.exit(f"{folder}/app.js has no '/*STRINGS*/ {{}}' marker")
    # "</" can't appear inside a <script>, so escape the slash in the text.
    text = json.dumps(strings, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    js = js.replace("/*STRINGS*/ {}", text)

    # Comments are for the sources only.
    html = re.sub(r"<!--.*?-->\n?", "", html, flags=re.S)
    css = re.sub(r"/\*.*?\*/\n?", "", css, flags=re.S)

    for tag, inline in (('<link rel="stylesheet" href="style.css">', f"<style>\n{css}</style>"),
                        ('<script src="app.js"></script>', f"<script>\n{js}</script>")):
        if tag not in html:
            sys.exit(f"{folder}/index.html has no {tag}")
        html = html.replace(tag, inline)
    return html


def header(folder, name, data):
    """The C++ header holding `data`, the gzipped page."""
    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    body = "\n".join(rows)
    return f"""// Generated by scripts/build-web.py from src/web/{folder}/ and src/web/strings.en.json.
// Don't edit; change the sources and run the script again.
#pragma once

#include <cstddef>
#include <cstdint>

namespace espmgr
{{
namespace web
{{

// The page, gzip-compressed; serve it with Content-Encoding: gzip.
inline constexpr uint8_t {name}[] = {{
{body}
}};
inline constexpr size_t {name}Size = sizeof({name});

}}  // namespace web
}}  // namespace espmgr
"""


def page_in_header(path):
    """The page stored in an existing header, or None if it can't be read."""
    if not path.exists():
        return None
    data = bytes(int(b, 16) for b in BYTE.findall(path.read_text(encoding="utf-8")))
    try:
        return gzip.decompress(data).decode("utf-8")
    except (OSError, EOFError, UnicodeDecodeError):
        return None


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="fail if a header is out of date instead of writing it")
    args = parser.parse_args()

    stale = []
    for folder, filename, name in PAGES:
        page = build_page(folder)
        path = GENERATED / filename
        if args.check:
            if page_in_header(path) != page:
                stale.append(path.relative_to(ROOT))
            continue
        # mtime=0 keeps the output the same from one run to the next.
        data = gzip.compress(page.encode("utf-8"), compresslevel=9, mtime=0)
        GENERATED.mkdir(exist_ok=True)
        path.write_text(header(folder, name, data), encoding="utf-8")
        print(f"{path.relative_to(ROOT)}: {len(page)} bytes, {len(data)} gzipped")

    if stale:
        for path in stale:
            print(f"{path} is out of date; run scripts/build-web.py and commit the result.",
                  file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
